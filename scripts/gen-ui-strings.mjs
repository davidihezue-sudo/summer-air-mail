// Lists the fixed wording that is built into the public site (headings, filters, form labels, buttons, season titles), so the
// Languages page can translate it. Regenerates src/i18n/builtin.ts:   node scripts/gen-ui-strings.mjs
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const SKIP_FILES = /(\/ui\/art\.tsx|\/ui\/Icons\.tsx|\/ui\/iconMap\.ts|\.test\.)/

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) yield* walk(p)
    else yield p
  }
}

const looksLikeWords = (s) => /^[A-Z][A-Za-z0-9'\u2019,.!?&:;()/\- ]*$/.test(s) && /[a-z]/.test(s) && s.length >= 3 && s.length <= 160 && !/\b(px|rem|https?)\b/.test(s)

/** Every built-in sentence or label that is written straight into the page code. */
export function extractBuiltinStrings(root = ROOT, uiDefaults = []) {
  const found = new Set()
  // JSX turns &rsquo; into a real apostrophe on the page, so the list holds what visitors actually see.
  const plain = (s) => s.replace(/&rsquo;|&#8217;/g, '\u2019').replace(/&lsquo;/g, '\u2018').replace(/&amp;/g, '&').replace(/&nbsp;/g, ' ').replace(/&quot;/g, '"').replace(/&apos;|&#39;/g, "'")
  const add = (s) => { const t = plain(s).replace(/\s+/g, ' ').trim(); if (looksLikeWords(t)) found.add(t) }
  for (const dir of ['src/components', 'src/pages']) {
    for (const file of walk(join(root, dir))) {
      if (!file.endsWith('.tsx') || SKIP_FILES.test(file.replaceAll('\\', '/'))) continue
      const src = readFileSync(file, 'utf8')
      // Text written between tags on one line: >Send<
      for (const m of src.matchAll(/>([^<>{}\n]{3,160})</g)) add(m[1])
      // Words in a few attributes: placeholder="..." aria-label="..." title="..." eyebrow="..." intro="..."
      for (const m of src.matchAll(/\b(?:placeholder|aria-label|title|eyebrow|intro|label)="([^"{}]{3,200})"/g)) add(m[1])
    }
  }
  // The season titles: copy: { workTitle: '...', ... }
  for (const file of readdirSync(join(root, 'src/themes'))) {
    if (!file.endsWith('.ts')) continue
    const src = readFileSync(join(root, 'src/themes', file), 'utf8')
    const block = /copy:\s*\{([\s\S]*?)\n\s*\},?/.exec(src)?.[1] ?? ''
    for (const m of block.matchAll(/:\s*'([^']+)'/g)) add(m[1])
  }
  const have = new Set(uiDefaults.map((s) => s.trim()))
  return [...found].filter((s) => !have.has(s)).sort((a, b) => a.localeCompare(b))
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const ui = readFileSync(join(ROOT, 'src/i18n/ui.ts'), 'utf8')
  const defaults = [...ui.matchAll(/:\s*'((?:[^'\\]|\\.)*)'/g)].map((m) => m[1].replace(/\\'/g, "'"))
  const list = extractBuiltinStrings(ROOT, defaults)
  const body = `// Generated by scripts/gen-ui-strings.mjs. Do not edit by hand. Fixed wording built into the public site, in English.\n// A language pack can translate any of these by using the English text as the key.\nexport const BUILTIN_STRINGS: string[] = ${JSON.stringify(list, null, 2)}\n`
  writeFileSync(join(ROOT, 'src/i18n/builtin.ts'), body)
  console.log(`wrote ${list.length} built-in strings (${relative(ROOT, join(ROOT, 'src/i18n/builtin.ts'))})`)
}
